async function ensureBucket() {
  if (!SUPABASE_URL || !SERVICE_KEY) {
    console.warn("Lewati pengaturan bucket: kredensial Supabase belum lengkap.");
    return;
  }

  const supabase = createClient(SUPABASE_URL, SERVICE_KEY, {
    auth: { persistSession: false },
  });

  const options = {
    public: true,
    fileSizeLimit: 6 * 1024 * 1024,
    allowedMimeTypes: ["image/jpeg", "image/png", "image/webp"],
  };

  const { data: buckets, error: listError } =
    await supabase.storage.listBuckets();

  if (listError) {
    console.warn("Tidak bisa membaca daftar bucket:", listError.message);
    return;
  }

  const exists = buckets?.some((bucket) => bucket.name === BUCKET);

  const { error } = exists
    ? await supabase.storage.updateBucket(BUCKET, options)
    : await supabase.storage.createBucket(BUCKET, options);

  if (error) {
    console.warn(`Bucket "${BUCKET}" gagal disiapkan:`, error.message);
    return;
  }

  console.log(
    `Bucket "${BUCKET}" siap (public, maksimal 6 MB, JPG/PNG/WEBP).`,
  );
}

async function main() {
  const client = new pg.Client({
    connectionString: DATABASE_URL,
    ssl: { rejectUnauthorized: false },
  });

  await client.connect();
  console.log("Terhubung ke database Supabase.");

  await client.query(SCHEMA_SQL);
  console.log("Tabel & RLS siap.");

  const username = process.env.SEED_ADMIN_USERNAME || "admin";
  const password = process.env.SEED_ADMIN_PASSWORD || "Kapita2026";

  const adminExists = await client.query(
    "select id from admins where username = $1 limit 1",
    [username],
  );

  if (adminExists.rowCount === 0) {
    const hash = await bcrypt.hash(password, 12);
    await client.query(
      "insert into admins (username, name, password_hash) values ($1, $2, $3)",
      [username, "Administrator", hash],
    );
    console.log(`Akun admin dibuat: ${username} / ${password}`);
  } else {
    console.log(`Akun admin "${username}" sudah ada (password tidak diubah).`);
  }

  const postCount = await client.query("select count(*)::int as total from posts");
  const total = postCount.rows[0].total;

  if (total === 0) {
    for (const post of SEED_POSTS) {
      const createdAt = new Date(
        Date.now() - post.daysAgo * 24 * 60 * 60 * 1000,
      ).toISOString();

      await client.query(
        `insert into posts
          (title, slug, category, excerpt, content, image, is_published, created_at, updated_at)
         values ($1, $2, $3, $4, $5, $6, true, $7, $7)`,
        [
          post.title,
          post.slug,
          post.category,
          post.excerpt,
          post.content,
          post.image,
          createdAt,
        ],
      );
    }
    console.log(`${SEED_POSTS.length} berita contoh ditambahkan.`);
  } else {
    console.log(`Tabel posts sudah berisi ${total} tulisan; seed dilewati.`);
  }

  await client.end();
  await ensureBucket();

  console.log("Migrasi selesai.");
}

main().catch((error) => {
  console.error("Migrasi gagal:", error.message);
  process.exit(1);
});
