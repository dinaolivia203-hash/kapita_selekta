if (!DATABASE_URL) {
  console.error(
    "DATABASE_URL belum diisi. Ambil connection string dari Supabase → Project Settings → Database → Connection string (URI).",
  );
  process.exit(1);
}

const SCHEMA_SQL = `
create table if not exists admins (
  id bigint generated by default as identity primary key,
  username text not null unique,
  name text not null,
  password_hash text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists posts (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text not null unique,
  category text not null check (category in ('berita', 'prestasi', 'kegiatan')),
  excerpt text not null default '',
  content text not null,
  image text,
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_posts_published
  on posts (is_published, created_at desc);

create table if not exists login_attempts (
  id bigint generated by default as identity primary key,
  username text not null,
  ip text not null,
  attempted_at timestamptz not null default now()
);

create index if not exists idx_attempts_time
  on login_attempts (attempted_at);

alter table admins enable row level security;
alter table posts enable row level security;
alter table login_attempts enable row level security;
`;

